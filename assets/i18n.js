function getSavedLanguage() {
  return localStorage.getItem('cv_preferred_language') || 'id';
}

function setLanguage(lang) {
  if (!translations[lang]) lang = 'id';
  localStorage.setItem('cv_preferred_language', lang);
  document.documentElement.lang = lang;

  // Update text nodes
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key] !== undefined) {
      el.textContent = translations[lang][key];
    }
  });

  // Update HTML nodes
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const key = el.getAttribute('data-i18n-html');
    if (translations[lang][key] !== undefined) {
      el.innerHTML = translations[lang][key];
    }
  });

  // Update toggle buttons UI
  document.querySelectorAll('.lang-toggle-indicator').forEach((indicator) => {
    if (lang === 'id') {
      indicator.innerHTML = '<span class="text-cyanGlow font-bold">ID</span><span class="text-slate-500 mx-0.5">/</span><span class="text-slate-400">EN</span>';
    } else {
      indicator.innerHTML = '<span class="text-slate-400">ID</span><span class="text-slate-500 mx-0.5">/</span><span class="text-cyanGlow font-bold">EN</span>';
    }
  });
}

function toggleLanguage() {
  const current = getSavedLanguage();
  const next = current === 'id' ? 'en' : 'id';
  setLanguage(next);
}

// Initialize on load
document.addEventListener('DOMContentLoaded', () => {
  const lang = getSavedLanguage();
  setLanguage(lang);

  document.querySelectorAll('.lang-toggle-btn').forEach((btn) => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      toggleLanguage();
    });
  });
});
